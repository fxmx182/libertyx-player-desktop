/// <summary>Atalhos para montar a interface em código (as telas daqui são construídas assim).</summary>
public static class Ui
{
    public static IBrush Pincel(string chave) => (IBrush)Avalonia.Application.Current!.FindResource(chave)!;

    public static PathIcon Icone(string dados, double tam = 20, IBrush? cor = null)
    {
        var i = new PathIcon { Data = StreamGeometry.Parse(dados), Width = tam, Height = tam };
        if (cor != null) i.Foreground = cor;
        return i;
    }

    public static TextBlock Texto(string t, double tam = 14, FontWeight peso = FontWeight.Normal, string? classe = null)
    {
        var tb = new TextBlock { Text = t, FontSize = tam, FontWeight = peso, TextWrapping = TextWrapping.Wrap };
        if (classe != null) foreach (var c in classe.Split(' ')) tb.Classes.Add(c);
        return tb;
    }

    public static TextBlock Linha(string t, double tam = 14, FontWeight peso = FontWeight.Normal, string? classe = null)
    {
        var tb = Texto(t, tam, peso, classe);
        tb.TextWrapping = TextWrapping.NoWrap;
        tb.TextTrimming = TextTrimming.CharacterEllipsis;
        return tb;
    }

    public static Button Botao(string? texto, string? icone, string classe, Action? clique, double tamIcone = 18)
    {
        var b = new Button();
        foreach (var c in classe.Split(' ')) b.Classes.Add(c);
        if (icone != null && texto != null)
            b.Content = new StackPanel { Orientation = Orientation.Horizontal, Spacing = 8, Children = { Icone(icone, tamIcone), new TextBlock { Text = texto, VerticalAlignment = VerticalAlignment.Center } } };
        else if (icone != null) b.Content = Icone(icone, tamIcone);
        else b.Content = texto;
        if (clique != null) b.Click += (_, _) => clique();
        return b;
    }

    public static Button BotaoIcone(string icone, string dica, Action clique, string classe = "player", double tam = 22)
    {
        var b = Botao(null, icone, classe, clique, tam);
        ToolTip.SetTip(b, dica);
        return b;
    }

    public static StackPanel Pilha(double espaco = 10, Orientation o = Orientation.Vertical, params Control[] filhos)
    {
        var s = new StackPanel { Spacing = espaco, Orientation = o };
        s.Children.AddRange(filhos);
        return s;
    }

    public static Image Marca(double tam) => new()
    {
        Source = new Bitmap(AssetLoader.Open(new Uri("avares://LibertyXPlayer/Assets/marca.png"))), Width = tam, Height = tam,
    };

    /// <summary>A capa de um vídeo: a miniatura quando houver; antes disso, o ícone de filme no fundo escuro.</summary>
    public static Border Capa(double largura, double altura, out Image imagem)
    {
        imagem = new Image { Stretch = Stretch.UniformToFill };
        var g = new Grid();
        g.Children.Add(new PathIcon { Data = StreamGeometry.Parse(Icones.Quadro), Width = 30, Height = 30, Foreground = Pincel("Tenue") });
        g.Children.Add(imagem);
        return new Border { Classes = { "capa" }, Width = largura, Height = altura, Child = g };
    }

    /// <summary>A barrinha de quanto já foi visto, no pé da capa.</summary>
    public static Control Progresso(double fracao)
    {
        if (fracao <= 0.01) return new Panel();
        var g = new Grid { Height = 4, VerticalAlignment = VerticalAlignment.Bottom, ColumnDefinitions = new ColumnDefinitions($"{fracao.ToString(System.Globalization.CultureInfo.InvariantCulture)}*,{(1 - fracao).ToString(System.Globalization.CultureInfo.InvariantCulture)}*") };
        g.Children.Add(new Rectangle { Fill = Pincel("Ouro") });
        var resto = new Rectangle { Fill = new SolidColorBrush(Color.Parse("#66000000")) };
        Grid.SetColumn(resto, 1);
        g.Children.Add(resto);
        return g;
    }

    public static Border Selo(string texto, IBrush? fundo = null, IBrush? frente = null) => new()
    {
        Background = fundo ?? new SolidColorBrush(Color.Parse("#B3000000")), CornerRadius = new CornerRadius(6), Padding = new Thickness(6, 2),
        Child = new TextBlock { Text = texto, FontSize = 11, FontWeight = FontWeight.Bold, Foreground = frente ?? Brushes.White },
    };

    public static void Abrir(string url)
    {
        try
        {
            System.Diagnostics.Process.Start(OperatingSystem.IsWindows()
                ? new System.Diagnostics.ProcessStartInfo(url) { UseShellExecute = true }
                : new System.Diagnostics.ProcessStartInfo("xdg-open", url) { UseShellExecute = false });
        }
        catch { }
    }
}
